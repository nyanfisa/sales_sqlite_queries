CREATE TABLE IF NOT EXISTS coupons (
    id                   INTEGER PRIMARY KEY,
    code                 TEXT NOT NULL UNIQUE,
    coupon_type          TEXT NOT NULL CHECK (coupon_type IN ('PERCENT', 'AMOUNT')),
    value                REAL NOT NULL CHECK (value >= 0),
    start_at             TEXT NOT NULL,
    end_at               TEXT NOT NULL,
    status               TEXT NOT NULL CHECK (status IN ('NEW', 'ISSUED', 'USED', 'EXPIRED', 'CANCELLED')),
    issued_to_account_id INTEGER,
    FOREIGN KEY (issued_to_account_id) REFERENCES loyalty_accounts(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,
    CHECK (end_at >= start_at)
);

